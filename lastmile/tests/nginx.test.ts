/**
 * Tests for the lastmile atomic nginx include writer.
 */
import { describe, it, expect } from 'vitest';
import { writeNginxInclude, type NginxModuleDeps, type NginxWriteResult } from '../src/nginx.js';

const INCLUDE = '/etc/nginx/lastmile/s3ntiment.conf';
const CID = 'bafykbzacexamplecid';
const ARGS = {
  includePath: INCLUDE,
  domain: 's3ntiment.com',
  ensName: 's3ntiment.eth',
  cid: CID,
  s2sJsonPath: '/var/lib/lastmile/s3ntiment/s2s.json',
  gatewayBase: 'http://127.0.0.1:28080',
};
const TEST_CMD = 'sudo -n nginx -t';
const RELOAD_CMD = 'sudo -n nginx -s reload';

interface CapturedCall {
  op: string;
  args: unknown[];
}

function makeDeps(opts: {
  existingInclude?: string | null;
  okByCmd?: Record<string, boolean>;
  throwByCmd?: string[];
}): { deps: NginxModuleDeps; calls: CapturedCall[]; fs: Map<string, string> } {
  const fs = new Map<string, string>();
  if (opts.existingInclude !== null && opts.existingInclude !== undefined) {
    fs.set(INCLUDE, opts.existingInclude);
  }
  const calls: CapturedCall[] = [];
  const deps: NginxModuleDeps = {
    readFile: async (p) => {
      calls.push({ op: 'readFile', args: [p] });
      return fs.get(p) ?? null;
    },
    writeFile: async (p, c) => {
      calls.push({ op: 'writeFile', args: [p, c] });
      fs.set(p, c);
    },
    rename: async (from, to) => {
      calls.push({ op: 'rename', args: [from, to] });
      const v = fs.get(from);
      if (v === undefined) throw new Error(`rename: source missing: ${from}`);
      fs.delete(from);
      fs.set(to, v);
    },
    rm: async (p) => {
      calls.push({ op: 'rm', args: [p] });
      fs.delete(p);
    },
    run: async (cmd) => {
      calls.push({ op: 'run', args: [cmd] });
      if (opts.throwByCmd?.includes(cmd)) throw new Error(`command not found: ${cmd}`);
      return { ok: opts.okByCmd?.[cmd] ?? true, stdout: '', stderr: '' };
    },
  };
  return { deps, calls, fs };
}

function runCmds(calls: CapturedCall[]): string[] {
  return calls.filter((c) => c.op === 'run').map((c) => c.args[0] as string);
}

describe('renderNginxInclude (via writeNginxInclude)', () => {
  it('produces the exact handoff shape', async () => {
    const { deps, fs } = makeDeps({ existingInclude: 'old' });
    await writeNginxInclude(ARGS, deps);
    const expected = `# Generated by lastmile — do not edit manually.
set $s2s_cid bafykbzacexamplecid;

location /.well-known/s2s.json {
    alias /var/lib/lastmile/s3ntiment/s2s.json;
}

location / {
    proxy_pass http://127.0.0.1:28080/ipfs/$s2s_cid$uri;
    proxy_set_header Host 127.0.0.1;
    add_header X-S2S-ENS s3ntiment.eth always;
}
`;
    expect(fs.get(INCLUDE)).toBe(expected);
  });
});

describe('writeNginxInclude', () => {
  it('happy path: test ok -> reload ok, wrote:true', async () => {
    const { deps, fs, calls } = makeDeps({
      existingInclude: 'old-content',
      okByCmd: { [TEST_CMD]: true, [RELOAD_CMD]: true },
    });
    const res = await writeNginxInclude(ARGS, deps);
    expect(res).toEqual<NginxWriteResult>({
      includePath: INCLUDE,
      wrote: true,
      testOk: true,
      reloaded: true,
    });
    const content = fs.get(INCLUDE)!;
    expect(content).toContain('proxy_pass http://127.0.0.1:28080/ipfs/$s2s_cid$uri;');
    expect(content).toContain('add_header X-S2S-ENS s3ntiment.eth always;');
    expect(content).toContain('set $s2s_cid bafykbzacexamplecid;');
    expect(content).toContain('alias /var/lib/lastmile/s3ntiment/s2s.json;');
    // Backup preserved the previous include.
    expect(fs.get(`${INCLUDE}.lastmile-bak`)).toBe('old-content');
    // Temp file was consumed by the rename.
    expect(fs.get(`${INCLUDE}.lastmile-new`)).toBeUndefined();
    expect(runCmds(calls)).toEqual([TEST_CMD, RELOAD_CMD]);
  });

  it('is atomic: writes .lastmile-new before renaming it into place', async () => {
    const { deps, calls, fs } = makeDeps({ existingInclude: 'old' });
    await writeNginxInclude(ARGS, deps);
    const writeIdx = calls.findIndex(
      (c) => c.op === 'writeFile' && c.args[0] === `${INCLUDE}.lastmile-new`,
    );
    const renameIdx = calls.findIndex(
      (c) => c.op === 'rename' && c.args[0] === `${INCLUDE}.lastmile-new` && c.args[1] === INCLUDE,
    );
    expect(writeIdx).toBeGreaterThanOrEqual(0);
    expect(renameIdx).toBeGreaterThan(writeIdx);
    // The content written to the temp file is what ends up live.
    const writtenNew = (calls[writeIdx].args[1] as string).trim();
    expect(fs.get(INCLUDE)!.trim()).toBe(writtenNew);
  });

  it('fails closed on nginx -t failure: restores backup, wrote:false', async () => {
    const { deps, fs, calls } = makeDeps({
      existingInclude: 'old-content',
      okByCmd: { [TEST_CMD]: false },
    });
    const res = await writeNginxInclude(ARGS, deps);
    expect(res).toEqual<NginxWriteResult>({
      includePath: INCLUDE,
      wrote: false,
      testOk: false,
      reloaded: false,
    });
    // Previous include restored.
    expect(fs.get(INCLUDE)).toBe('old-content');
    // No reload was attempted.
    expect(runCmds(calls)).toEqual([TEST_CMD]);
  });

  it('fails closed when there was no previous include: removes it, wrote:false', async () => {
    const { deps, fs } = makeDeps({ existingInclude: null, okByCmd: { [TEST_CMD]: false } });
    const res = await writeNginxInclude(ARGS, deps);
    expect(res).toEqual<NginxWriteResult>({
      includePath: INCLUDE,
      wrote: false,
      testOk: false,
      reloaded: false,
    });
    expect(fs.has(INCLUDE)).toBe(false);
  });

  it('fails closed when the test command throws (e.g. not found)', async () => {
    const { deps, fs } = makeDeps({ existingInclude: 'old', throwByCmd: [TEST_CMD] });
    const res = await writeNginxInclude(ARGS, deps);
    expect(res.wrote).toBe(false);
    expect(res.testOk).toBe(false);
    expect(res.reloaded).toBe(false);
    expect(fs.get(INCLUDE)).toBe('old'); // restored
  });

  it('reports wrote:true, testOk:true, reloaded:false on reload failure', async () => {
    const { deps, fs, calls } = makeDeps({
      existingInclude: 'old',
      okByCmd: { [TEST_CMD]: true, [RELOAD_CMD]: false },
    });
    const res = await writeNginxInclude(ARGS, deps);
    expect(res).toEqual<NginxWriteResult>({
      includePath: INCLUDE,
      wrote: true,
      testOk: true,
      reloaded: false,
    });
    expect(fs.get(INCLUDE)).toContain('set $s2s_cid bafykbzacexamplecid;');
    expect(runCmds(calls)).toEqual([TEST_CMD, RELOAD_CMD]);
  });

  it('uses custom test/reload commands when provided', async () => {
    const { deps, calls } = makeDeps({});
    await writeNginxInclude(ARGS, deps, { testCmd: 'nginx -t -c /tmp/nginx.conf', reloadCmd: 'nginx -s reload' });
    expect(runCmds(calls)).toEqual(['nginx -t -c /tmp/nginx.conf', 'nginx -s reload']);
  });

  it('rethrows on an unexpected reload failure and keeps the validated include', async () => {
    const fs = new Map<string, string>();
    fs.set(INCLUDE, 'old');
    let ranTest = false;
    const deps: NginxModuleDeps = {
      readFile: async () => 'old',
      writeFile: async (p, c) => void fs.set(p, c),
      rename: async (from, to) => {
        const v = fs.get(from);
        if (v === undefined) throw new Error('boom');
        fs.delete(from);
        fs.set(to, v);
      },
      rm: async (p) => void fs.delete(p),
      run: async (cmd) => {
        if (cmd === TEST_CMD) {
          ranTest = true;
          return { ok: true, stdout: '', stderr: '' };
        }
        throw new Error('unexpected reload failure');
      },
    };
    await expect(writeNginxInclude(ARGS, deps)).rejects.toThrow('unexpected reload failure');
    expect(ranTest).toBe(true);
    // The validated include stays in place (not rolled back) despite the throw.
    expect(fs.get(INCLUDE)).toContain('set $s2s_cid bafykbzacexamplecid;');
    // Backup of the previous include is preserved.
    expect(fs.get(`${INCLUDE}.lastmile-bak`)).toBe('old');
  });

  it('rethrows on an unexpected swap failure and restores the previous include', async () => {
    const fs = new Map<string, string>();
    fs.set(INCLUDE, 'old');
    const deps: NginxModuleDeps = {
      readFile: async () => 'old',
      writeFile: async (p, c) => void fs.set(p, c),
      rename: async (from, to) => {
        // Fail only the atomic swap into place.
        if (from === `${INCLUDE}.lastmile-new` && to === INCLUDE) throw new Error('swap boom');
        const v = fs.get(from);
        if (v === undefined) throw new Error('boom');
        fs.delete(from);
        fs.set(to, v);
      },
      rm: async (p) => void fs.delete(p),
      run: async () => ({ ok: true, stdout: '', stderr: '' }),
    };
    await expect(writeNginxInclude(ARGS, deps)).rejects.toThrow('swap boom');
    // Best-effort restore reinstalled the previous content.
    expect(fs.get(INCLUDE)).toBe('old');
  });
});
