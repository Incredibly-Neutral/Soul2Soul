/**
 * lastmile — atomic nginx include rewrite (fail-closed + self-healing).
 *
 * Strategy: write the new include to a temp sibling, back up the current
 * include, atomically rename the temp into place, then run `nginx -t`. If the
 * test fails (or the command is missing/throws), the previous include is
 * restored (or removed when there was none) and the result reports
 * `wrote:false`. Only on a passing test is nginx reloaded.
 */
export interface NginxWriteResult {
  includePath: string;
  wrote: boolean;
  testOk: boolean;
  reloaded: boolean;
}

/** Filesystem + process deps, injectable for tests. */
export interface NginxModuleDeps {
  /** null when the file does not exist */
  readFile: (path: string) => Promise<string | null>;
  writeFile: (path: string, content: string) => Promise<void>;
  rename: (from: string, to: string) => Promise<void>;
  rm: (path: string) => Promise<void>;
  run: (cmd: string) => Promise<{ ok: boolean; stdout: string; stderr: string }>;
}

export interface WriteNginxIncludeArgs {
  /** absolute path of the include file to (re)write */
  includePath: string;
  /** e.g. s3ntiment.com */
  domain: string;
  /** e.g. s3ntiment.eth */
  ensName: string;
  /** current IPFS CID */
  cid: string;
  /** absolute path of the s2s.json served via `alias` */
  s2sJsonPath: string;
  /** base the nginx proxy_pass points at, e.g. http://127.0.0.1:28080 */
  gatewayBase: string;
}

export interface NginxCmds {
  testCmd?: string;
  reloadCmd?: string;
}

const DEFAULT_TEST_CMD = "sudo -n nginx -t";
const DEFAULT_RELOAD_CMD = "sudo -n nginx -s reload";

/** Render the exact nginx include shape lastmile hands off. */
export function renderNginxInclude(args: WriteNginxIncludeArgs): string {
  const { cid, ensName, s2sJsonPath, gatewayBase } = args;
  return [
    "# Generated by lastmile — do not edit manually.",
    `set $s2s_cid ${cid};`,
    "",
    "location /.well-known/s2s.json {",
    `    alias ${s2sJsonPath};`,
    "}",
    "",
    "location / {",
    `    proxy_pass ${gatewayBase}/ipfs/$s2s_cid$uri;`,
    "    proxy_set_header Host 127.0.0.1;",
    `    add_header X-S2S-ENS ${ensName} always;`,
    "}",
    "",
  ].join("\n");
}

/**
 * Atomically rewrite an nginx include and validate/reload it.
 *
 * Fail-closed: if `nginx -t` fails (or the command throws, e.g. not found),
 * the previous include is restored (or removed if there was none) and the
 * result reports `wrote:false`. Unexpected errors during any step trigger a
 * best-effort restore of the include path before rethrowing.
 */
export async function writeNginxInclude(
  args: WriteNginxIncludeArgs,
  deps: NginxModuleDeps,
  cmds?: NginxCmds,
): Promise<NginxWriteResult> {
  const testCmd = cmds?.testCmd ?? DEFAULT_TEST_CMD;
  const reloadCmd = cmds?.reloadCmd ?? DEFAULT_RELOAD_CMD;
  const newPath = `${args.includePath}.lastmile-new`;
  const bakPath = `${args.includePath}.lastmile-bak`;
  let hadBackup = false;
  let testPassed = false;

  try {
    // 1. Write the new content to a temp sibling (never clobber the live file).
    await deps.writeFile(newPath, renderNginxInclude(args));

    // 2. Preserve the current include as a backup, if one exists.
    const current = await deps.readFile(args.includePath);
    if (current !== null) {
      await deps.writeFile(bakPath, current);
      hadBackup = true;
    }

    // 3. Atomic swap into place.
    await deps.rename(newPath, args.includePath);

    // 4. Validate with nginx -t, then reload on success.
    let testOk = false;
    try {
      const test = await deps.run(testCmd);
      testOk = test.ok;
    } catch {
      // Command missing / run() throwing counts as a failed test (fail closed).
      testOk = false;
    }
    testPassed = testOk;

    if (!testOk) {
      // Fail-closed: restore the previous include (or remove the new one).
      if (hadBackup) {
        await deps.rename(bakPath, args.includePath);
      } else {
        await deps.rm(args.includePath);
      }
      return { includePath: args.includePath, wrote: false, testOk: false, reloaded: false };
    }

    // A throwing reload propagates (unexpected error) without rolling back
    // the now-validated include: once the test passed, the include is already
    // in a valid state, so the best-effort restore below must not undo it.
    const reload = await deps.run(reloadCmd);
    return { includePath: args.includePath, wrote: true, testOk: true, reloaded: reload.ok };
  } catch (err) {
    // Best-effort restore on unexpected errors: only reinstall the backup,
    // never delete a live include, and never undo a validated include.
    if (hadBackup && !testPassed) {
      try {
        await deps.rename(bakPath, args.includePath);
      } catch {
        // Ignore restore failure; rethrow the original error below.
      }
    }
    throw err;
  }
}
